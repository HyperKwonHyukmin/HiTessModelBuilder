using Cmb.Core.Model;
using Cmb.Core.Model.Context;
using Cmb.Pipeline.Core;
using Cmb.Pipeline.Spatial;

namespace Cmb.Pipeline.Stages;

/// <summary>
/// CBEAM 그래프 connected component 동등성을 검사하여, 자동 생성 RBE2
/// (FREE_END_RBE / PRESERVED_FREE_END / FINAL_MESH_PROXIMITY) 의 dep 중
/// indep 와 이미 같은 컴포넌트에 속한 항목을 제거한다.
///
/// RbeBeamDeduplicateStage 는 0-hop (직접 edge) 만 검사하므로 매개 노드
/// 1개 이상을 거치는 위상 중복은 잡지 못한다. 이 stage 는 그 보완책으로,
/// FinalValidationStage 직전에 실행된다.
///
/// 안전 정책: 사용자 수동 RBE (UBOLT/EQUIPMENT/VALV/TRAP/FILT/EXP) 는
/// 화이트리스트에 포함하지 않으므로 절대 건드리지 않는다.
/// </summary>
public sealed class RedundantBridgeRbeRemoveStage : IPipelineStage
{
    public string Name => "RedundantBridgeRbeRemove";

    // 이 화이트리스트의 remark 만 bridge-dedup 대상이다.
    // 주의: LoopCloseProximityStage 의 "LOOP_CLOSE_PROXIMITY" 는 의도적으로 제외한다 —
    // 같은 CBEAM 컴포넌트라도 위상상 멀어 일부러 추가한 loop-close RBE2 이므로 여기서 제거하면 안 된다.
    private static readonly HashSet<string> AutoGeneratedRemarks = new(StringComparer.Ordinal)
    {
        "FREE_END_RBE",
        "PRESERVED_FREE_END",
        "FINAL_MESH_PROXIMITY",
    };

    public bool Execute(StageContext ctx)
    {
        var model = ctx.Model;

        // CBEAM 만으로 UnionFind 구성 (RBE 는 포함 X — RBE 의 redundancy 판정이 목적)
        var nodeIds = model.Nodes.Select(n => n.Id);
        var uf = new UnionFind(nodeIds);
        foreach (var e in model.Elements)
            uf.Union(e.StartNodeId, e.EndNodeId);

        int rbeRemoved = 0;
        int depRemoved = 0;
        var toRemove   = new List<int>();

        for (int i = 0; i < model.Rigids.Count; i++)
        {
            var rigid = model.Rigids[i];
            if (!AutoGeneratedRemarks.Contains(rigid.Remark)) continue;

            int indep     = rigid.IndependentNodeId;
            int indepRoot = uf.Find(indep);

            var keptDeps    = new List<int>(rigid.DependentNodeIds.Count);
            int removedHere = 0;

            foreach (int dep in rigid.DependentNodeIds)
            {
                if (uf.Find(dep) == indepRoot)
                {
                    removedHere++;
                    ctx.AddTrace(TraceAction.ElementRemoved, Name,
                        elementId: rigid.Id, nodeId: dep, relatedNodeId: indep,
                        note: $"RBE dep N{dep} ↔ indep N{indep} already in same CBEAM component — dep removed");
                    ctx.AddDiagnostic(DiagnosticSeverity.Warning, "RBE2_REDUNDANT_BRIDGE",
                        $"RBE {rigid.Id} ({rigid.Remark}): dep N{dep} ↔ indep N{indep} already topologically connected via CBEAM graph; dep removed.",
                        elementId: rigid.Id, nodeId: dep);
                }
                else
                {
                    keptDeps.Add(dep);
                }
            }

            if (removedHere == 0) continue;
            depRemoved += removedHere;

            if (keptDeps.Count == 0)
            {
                // BOX UBOLT 는 화이트리스트(UBOLT)에 없지만, 방어적으로 동일 패턴 유지
                if (IsDeferredBoxUbolt(rigid))
                {
                    ctx.AddDiagnostic(DiagnosticSeverity.Warning, "BOX_UBOLT_EMPTY_AFTER_BRIDGE_DEDUP",
                        $"BOX UBOLT RBE {rigid.Id} has no remaining deps after bridge-dedup.",
                        elementId: rigid.Id);
                    continue;
                }

                toRemove.Add(rigid.Id);
                rbeRemoved++;
                ctx.AddTrace(TraceAction.ElementRemoved, Name,
                    elementId: rigid.Id, nodeId: indep,
                    note: "auto-generated RBE2 emptied after bridge-dedup — removed");
                continue;
            }

            // 일부 dep만 제거 — RigidElement 는 immutable 이므로 교체
            model.Rigids[i] = new RigidElement(
                rigid.Id, indep, keptDeps,
                rigid.Remark, rigid.SourceName, rigid.Cm, rigid.DetailRemark);
        }

        if (toRemove.Count > 0)
        {
            var removeSet = toRemove.ToHashSet();
            model.Rigids.RemoveAll(r => removeSet.Contains(r.Id));
        }

        if (depRemoved > 0 || rbeRemoved > 0)
            ctx.AddDiagnostic(DiagnosticSeverity.Info, "RBE_BRIDGE_DEDUP_SUMMARY",
                $"{depRemoved} dep(s) removed, {rbeRemoved} empty auto-RBE2(s) removed (CBEAM connected-component duplicates).");

        return true;
    }

    // NodeEquivalenceStage 의 패턴 그대로 (`NodeEquivalenceStage.cs:131-133`)
    private static bool IsDeferredBoxUbolt(RigidElement rigid)
        => rigid.Remark == "UBOLT" &&
           string.Equals(rigid.DetailRemark, "BOX", StringComparison.OrdinalIgnoreCase);
}
